    await UHttpClient.send(
      method: "POST",
      endpoint: "${U.baseUrl}/txn/Read",
      body: p.toMap().add("apiKey", U.apiKey).add("token", ULocalStorage.getToken()),
      onSuccess: (final Response r) {
        final UResponse<List<UTxnResponse>> ok = UResponse<List<UTxnResponse>>.fromJson(
          r.body,
          (final dynamic i) => List<UTxnResponse>.from((i as List<dynamic>).map((final dynamic x) => UTxnResponse.fromMap(x))),
        );
        result = (ok, null, null);
        onOk?.call(ok);
      },
      onError: (final Response r) {
        final UEmptyResponse err = UEmptyResponse.fromJson(r.body);
        result = (null, err, null);
        onError?.call(err);
      },
      onException: (final String e) {
        result = (null, null, e);
        onException?.call(e);
      },
    );
    return result;
  }

